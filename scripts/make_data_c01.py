#!/usr/bin/env python3
"""Build the synthetic ward export the Programming01 notebooks work on.

Everything is fake and seeded: no patient data ever enters this repository, and
`make data` reproduces byte-identical files anywhere. The tree is shaped to make
the notebook's exercises meaningful: several sub-directories, a filename with a
space in it, one deliberately empty file, and a log with a few error lines.

Usage: make_data_c01.py [outdir]      (default: Programming01/data)
"""

from __future__ import annotations

import sys
from pathlib import Path
from random import Random

WARDS = ["ICU", "ICU", "CARDIO", "CARDIO", "GERIA", "PEDIA", "ONCO"]
OUTCOMES = ["discharged", "discharged", "discharged", "transferred", "deceased"]
SEXES = ["F", "M"]


def patients(rng: Random, n: int = 240) -> list[str]:
    """The main cohort table: one row per stay, a few holes, ISO dates."""
    rows = ["patient_id,age,sex,ward,admission,los_days,outcome"]
    for i in range(1, n + 1):
        ward = rng.choice(WARDS)
        age = max(1, min(99, int(rng.gauss(72 if ward == "GERIA" else 58, 16))))
        if ward == "PEDIA":
            age = rng.randint(1, 17)
        month, day = rng.randint(1, 12), rng.randint(1, 28)
        los = round(abs(rng.gauss(9 if ward == "ICU" else 5, 4)) + 0.5, 1)
        outcome = rng.choice(OUTCOMES) if ward == "ICU" else rng.choice(OUTCOMES[:4])
        # ~4% of stays are missing an age, as in any real export
        age_s = "" if rng.random() < 0.04 else str(age)
        rows.append(
            f"P{i:04d},{age_s},{rng.choice(SEXES)},{ward},"
            f"2024-{month:02d}-{day:02d},{los},{outcome}"
        )
    return rows


def ecg_file(rng: Random, patient: str, minutes: int = 2) -> list[str]:
    """A short, semicolon-separated ECG export, a different dialect on purpose."""
    rows = ["t_s;lead_II_mV"]
    hr = rng.uniform(52, 118)
    for k in range(minutes * 60):
        rows.append(
            f"{k}.0;{rng.gauss(0, 0.12) + (0.9 if k % max(1, int(60 / (hr / 60))) == 0 else 0):.3f}"
        )
    return rows


def build(out: Path) -> None:
    rng = Random(20260908)
    (out / "ecg").mkdir(parents=True, exist_ok=True)
    (out / "exports").mkdir(parents=True, exist_ok=True)
    (out / "notes").mkdir(parents=True, exist_ok=True)

    cohort = patients(rng)
    (out / "patients.csv").write_text("\n".join(cohort) + "\n")

    # one ECG per patient, for the first 60 patients only: the tree is uneven,
    # which is the point of the "how many are missing a trace?" exercise
    ids = [row.split(",")[0] for row in cohort[1:]]
    for pid in ids[:60]:
        (out / "ecg" / f"{pid}.csv").write_text("\n".join(ecg_file(rng, pid)) + "\n")
    # one trace arrived empty from the recorder
    (out / "ecg" / f"{ids[17]}.csv").write_text("")

    # the real world puts spaces in filenames; the notebook makes them quote it
    (out / "exports" / "Patient Records 2024.csv").write_text(
        "\n".join(cohort[:26]) + "\n"
    )

    for pid in ids[:12]:
        (out / "notes" / f"{pid}.txt").write_text(
            f"Ward round note for {pid}.\n"
            f"{'Patient stable, continue current management.' if rng.random() > 0.35 else 'Escalated to ICU overnight, sepsis suspected.'}\n"
        )

    log = ["2024-03-01 08:00:12 INFO  export started"]
    for pid in ids[:40]:
        if rng.random() < 0.12:
            log.append(
                f"2024-03-01 08:0{rng.randint(0, 9)}:{rng.randint(10, 59)} "
                f"ERROR could not read trace for {pid}"
            )
        else:
            log.append(
                f"2024-03-01 08:0{rng.randint(0, 9)}:{rng.randint(10, 59)} "
                f"INFO  wrote ecg/{pid}.csv"
            )
    log.append("2024-03-01 08:12:44 INFO  export finished")
    (out / "export.log").write_text("\n".join(log) + "\n")

    (out / "README.md").write_text(
        "# Synthetic ward export\n\n"
        "Entirely fabricated data, generated by `scripts/make_data_c01.py`.\n"
        "No real patient is represented here.\n"
    )
    print(f"{out}: {sum(1 for _ in out.rglob('*') if _.is_file())} files")


def main() -> None:
    build(Path(sys.argv[1] if len(sys.argv) > 1 else "Programming01/data"))


if __name__ == "__main__":
    main()
